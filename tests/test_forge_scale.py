def legacy_synthesize_rows(plan, seed: int, rows_per_entity: int) -> Dict[str, List[Dict]]:
    """The skeleton's synthesizer as r2g 0.10.0 shipped it, kept verbatim as the
    reference the stream must reproduce with no knobs set. CDF commits suites
    generated by it, so a stream that drifted from it would move every one."""
    rng = random.Random(seed)
    rows: Dict[str, List[Dict]] = {}

    def value(json_type: str, prop: str):
        if json_type == "integer":
            return rng.randrange(0, 100_000)
        if json_type == "float":
            return round(rng.uniform(0, 100_000), 6)
        if json_type == "boolean":
            return rng.random() < 0.5
        return f"{prop}-{rng.randrange(0, 100_000):05d}"

    for table in plan.tables:
        key = table.primary_key.name
        fk_parents = [
            (fk, [r[fk.references_column or "id"] for r in rows[fk.references]])
            for fk in table.foreign_keys
        ]
        out = []
        for i in range(1, rows_per_entity + 1):
            row = {key: i}
            for fk, parent_ids in fk_parents:
                row[fk.name] = rng.choice(parent_ids)
            for col in table.properties:
                row[col.name] = value(col.json_type, col.prop)
            out.append(row)
        rows[table.table] = out
    return rows


