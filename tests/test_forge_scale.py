class TestScaleDocument:
    def test_round_trips_through_its_document(self):
        doc = {
            "rows": {"Contact": 50, "Account": 5},
            "relationships": {
                "contactsToAccounts": {"distribution": "zipf", "exponent": 1.2, "nullRate": 0.1}
            },
        }
        scale = ForgeScale.from_document(doc)
        assert scale.document() == {
            "rows": {"Account": 5, "Contact": 50},
            "relationships": {
                "contactsToAccounts": {"distribution": "zipf", "exponent": 1.2, "nullRate": 0.1}
            },
        }
        assert ForgeScale.from_document(scale.document()) == scale

    def test_defaults_are_left_out_of_the_document(self):
        scale = ForgeScale.from_document(
            {"relationships": {"contactsToAccounts": {"distribution": "uniform"}}}
        )
        assert scale.document() == {} and scale.is_default
        assert ForgeScale.from_document(None).is_default

    @pytest.mark.parametrize(
        "doc, match",
        [
            ([], "must be a mapping"),
            ({"rowz": {}}, "malformed forge scale"),
            ({"rows": {"Account": 0}}, "must be an integer >= 1"),
            ({"rows": {"Account": "many"}}, "malformed forge scale"),
            ({"relationships": {"r": {"distribution": "zipf"}}}, "needs an exponent"),
            ({"relationships": {"r": {"distribution": "zipf", "exponent": 0}}}, "> 0"),
            ({"relationships": {"r": {"distribution": "zipf", "exponent": -1}}}, "> 0"),
            ({"relationships": {"r": {"distribution": "uniform", "exponent": 1}}}, "only applies"),
            ({"relationships": {"r": {"distribution": "pareto"}}}, "malformed forge scale"),
            ({"relationships": {"r": {"nullRate": 1.0}}}, r"\[0, 1\)"),
            ({"relationships": {"r": {"nullRate": -0.1}}}, r"\[0, 1\)"),
            ({"relationships": {"r": {"fanout": 3}}}, "malformed forge scale"),
        ],
    )
    def test_malformed_knobs_are_refused_by_name(self, doc, match):
        with pytest.raises(ForgeError, match=match):
            ForgeScale.from_document(doc)

    def test_a_knob_naming_no_entity_is_refused(self):
        with pytest.raises(ForgeError, match=r"rows for \['Acount'\]"):
            synthesize_rows(skeleton_plan(), 1, 3, ForgeScale.from_document({"rows": {"Acount": 3}}))

    def test_a_knob_naming_no_relationship_is_refused(self):
        scale = ForgeScale.from_document({"relationships": {"contactsToAccount": {"nullRate": 0.5}}})
        with pytest.raises(ForgeError, match="contactsToAccount"):
            plan_schema(ForgeOntology.from_conceptual(skeleton_conceptual()), scale)
        with pytest.raises(ForgeError, match="contactsToAccount"):
            stream_rows(skeleton_plan(), 1, 3, scale)


