def _read_csv_chunks(out: Path, target: Dict[str, Any]) -> List[List[str]]:
    records = []
    for f in target["files"]:
        with open(out / f["path"], encoding="utf-8", newline="") as fh:
            records.extend(csv.reader(fh))
    return records


