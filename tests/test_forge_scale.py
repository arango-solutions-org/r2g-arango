# ── distributions match their knobs ──────────────────────────────────────────


def _chi_square_bound(df: int) -> float:
    """A bound the chi-square statistic exceeds with probability far below 1e-6
    (Wilson–Hilferty, z = 5.5)."""
    z = 5.5
    return df * (1 - 2 / (9 * df) + z * math.sqrt(2 / (9 * df))) ** 3


class TestDistributions:
    @pytest.mark.parametrize("n, s", [(1, 1.0), (2, 0.5), (50, 1.0), (1000, 1.2), (10**6, 2.0)])
    def test_zipf_sampler_matches_the_exact_pmf(self, n, s):
        sampler = ZipfSampler(n, s)
        rng = random.Random(f"zipf-{n}-{s}")
        draws = 60_000
        counts = Counter(sampler.sample(rng) for _ in range(draws))
        assert min(counts) >= 1 and max(counts) <= n
        norm = math.fsum(k ** -s for k in range(1, min(n, 10**6) + 1))
        for k in range(1, min(n, 8) + 1):
            p = k**-s / norm
            se = math.sqrt(p * (1 - p) / draws)
            assert abs(counts[k] / draws - p) < 5 * se + 1e-9, (k, counts[k] / draws, p)

    def test_zipf_sampler_goodness_of_fit(self):
        n, s, draws = 200, 1.1, 100_000
        sampler = ZipfSampler(n, s)
        rng = random.Random(4)
        counts = Counter(sampler.sample(rng) for _ in range(draws))
        probs = [sampler.probability(k) for k in range(1, n + 1)]
        # Bucket the tail so every expected count is at least 5.
        observed, expected, acc_o, acc_e = [], [], 0, 0.0
        for k in range(1, n + 1):
            acc_o += counts[k]
            acc_e += probs[k - 1] * draws
            if acc_e >= 5:
                observed.append(acc_o)
                expected.append(acc_e)
                acc_o, acc_e = 0, 0.0
        if acc_e:
            observed[-1] += acc_o
            expected[-1] += acc_e
        chi2 = sum((o - e) ** 2 / e for o, e in zip(observed, expected))
        assert chi2 < _chi_square_bound(len(observed) - 1), chi2

    def test_zipf_refuses_bad_parameters(self):
        with pytest.raises(ForgeError):
            ZipfSampler(0, 1.0)
        with pytest.raises(ForgeError):
            ZipfSampler(10, 0.0)
        with pytest.raises(ForgeError):
            ZipfSampler(10, float("nan"))

    def test_zipf_fanout_through_the_stream(self):
        """Children pick parent k with probability ~ k^-s: parent 1 is busiest
        and the top parents' shares match the pmf."""
        s, parents, children = 1.0, 500, 50_000
        scale = ForgeScale.from_document(
            {
                "rows": {"Account": parents, "Contact": children, "Ticket": 1},
                "relationships": {"contactsToAccounts": {"distribution": "zipf", "exponent": s}},
            }
        )
        counts = Counter(
            r["account_id"] for t, r in stream_rows(skeleton_plan(), 8, 1, scale) if t == "contacts"
        )
        norm = math.fsum(k**-s for k in range(1, parents + 1))
        for k in (1, 2, 3, 10):
            p = k**-s / norm
            assert abs(counts[k] / children - p) < 5 * math.sqrt(p * (1 - p) / children), k
        assert counts.most_common(1)[0][0] == 1
        # Mean fan-out is the row ratio whatever the skew.
        assert sum(counts.values()) / parents == children / parents

    def test_uniform_fanout_is_flat(self):
        parents, children = 100, 50_000
        scale = ForgeScale.from_document(
            {"rows": {"Account": parents, "Contact": children, "Ticket": 1}}
        )
        counts = Counter(
            r["account_id"] for t, r in stream_rows(skeleton_plan(), 8, 1, scale) if t == "contacts"
        )
        expected = children / parents
        chi2 = sum((counts[k] - expected) ** 2 / expected for k in range(1, parents + 1))
        assert chi2 < _chi_square_bound(parents - 1), chi2
        assert max(counts.values()) < 2 * expected  # no hot parent

    def test_null_rate(self):
        rate, children = 0.25, 40_000
        scale = ForgeScale.from_document(
            {
                "rows": {"Contact": children},
                "relationships": {"contactsToAccounts": {"nullRate": rate}},
            }
        )
        nulls = sum(
            1
            for t, r in stream_rows(skeleton_plan(), 2, 10, scale)
            if t == "contacts" and r["account_id"] is None
        )
        se = math.sqrt(rate * (1 - rate) / children)
        assert abs(nulls / children - rate) < 5 * se


