class TestSelfLinks:
    def test_a_class_linked_to_itself_is_accepted_and_planned(self):
        plan = org_plan()
        employees = plan.table("employees")
        fks = {c.name: c for c in employees.foreign_keys}
        assert fks["employee_id"].references == "employees"
        assert fks["employee_id"].optional and fks["employee_id"].nullable
        assert not fks["department_id"].optional
        edge = next(e for e in plan.edges if e.self_link)
        assert edge.relationship == "employeesToEmployees"
        assert edge.edge_collection == "employees_to_employees" and edge.optional

    def test_cycles_between_classes_are_still_refused(self):
        doc = org_conceptual()
        doc["relationships"].append(
            {
                "type": expected_relationship_type("Department", "Employee"),
                "fromEntity": "Department",
                "toEntity": "Employee",
            }
        )
        with pytest.raises(ForgeError, match="cycle"):
            plan_schema(ForgeOntology.from_conceptual(doc))

    @pytest.mark.parametrize(
        "knobs",
        [{}, {"distribution": "zipf", "exponent": 1.5}, {"nullRate": 0.3}],
        ids=["uniform", "zipf", "null-rate"],
    )
    def test_every_link_names_an_earlier_row(self, knobs):
        scale = ForgeScale.from_document(
            {"rows": {"Employee": 5_000}, "relationships": {"employeesToEmployees": knobs}}
        )
        employees = synthesize_rows(org_plan(scale), 13, 4, scale)["employees"]
        assert employees[0]["employee_id"] is None  # row 1 is a root on every seed
        for row in employees:
            manager = row["employee_id"]
            assert manager is None or 1 <= manager < row["id"]
        # So the links form a forest: following managers always terminates.
        managers = {r["id"]: r["employee_id"] for r in employees}
        depth = {}
        for i in sorted(managers):
            depth[i] = 0 if managers[i] is None else depth[managers[i]] + 1
        assert max(depth.values()) > 1  # a real hierarchy, not a star of roots

    def test_uniform_self_link_depth_is_logarithmic(self):
        """A random recursive tree: mean depth ~ ln(n). Deep enough for a
        reachability workload, shallow enough to be a plausible org chart."""
        n = 20_000
        scale = ForgeScale.from_document({"rows": {"Employee": n}})
        employees = synthesize_rows(org_plan(), 21, 3, scale)["employees"]
        depth: Dict[int, int] = {}
        for r in employees:
            depth[r["id"]] = 0 if r["employee_id"] is None else depth[r["employee_id"]] + 1
        mean = sum(depth.values()) / n
        assert abs(mean - math.log(n)) < 1.5, mean

    def test_ddl_declares_a_nullable_self_reference(self):
        ontology = ForgeOntology.from_conceptual(org_conceptual())
        ddl = generate(ontology, "postgres", seed=1, rows_per_entity=4).ddl
        assert "    employee_id bigint,\n" in ddl  # nullable: no NOT NULL
        assert "    department_id bigint NOT NULL,\n" in ddl
        assert "FOREIGN KEY (employee_id) REFERENCES employees (id)" in ddl
        load = generate(ontology, "postgres", seed=1, rows_per_entity=4).load_sql
        assert "INSERT INTO employees (id, department_id, employee_id, full_name) VALUES (1, " in load
        assert ", NULL, " in load

    def test_clickhouse_makes_the_self_reference_nullable(self):
        ddl = generate(ForgeOntology.from_conceptual(org_conceptual()), "clickhouse", seed=1).ddl
        assert "employee_id Nullable(Int64) COMMENT" in ddl
        assert "department_id Int64 COMMENT" in ddl

    def test_arango_has_no_edge_for_a_root(self):
        ontology = ForgeOntology.from_conceptual(org_conceptual())
        artifacts = generate(ontology, "arango", seed=1, rows_per_entity=6)
        docs = project_documents(json.loads(artifacts.ddl), artifacts.rows)
        assert len(docs["employees"]) == 6
        assert len(docs["employees_to_employees"]) == 5  # row 1 has no manager
        assert all(e["_to"] != "employees/None" for e in docs["employees_to_employees"])
        # The loader script's own copy of the projection agrees.
        namespace: Dict[str, Any] = {}
        exec(artifacts.load_sql.split("def main()")[0], namespace)
        manifest = json.loads(artifacts.ddl)
        assert namespace["project_documents"](manifest, artifacts.rows) == docs

    def test_forward_pipeline_re_derives_the_self_relationship(self):
        """Auto-Map and the CSI emitter, in memory: the self-referencing FK comes
        back as the relationship the ontology declared (ADR-0006 D-3)."""
        from r2g.config import ConfigManager
        from r2g.csi import mapping_to_csi
        from r2g.types import Column, ForeignKey, Schema, Table

        plan = org_plan()
        pg = get_dialect("postgres")
        tables = {}
        for t in plan.tables:
            tables[t.table] = Table(
                name=t.table,
                columns=[
                    Column(
                        name=c.name,
                        data_type=pg.type_for_json[c.json_type],
                        is_nullable=c.nullable,
                        is_primary_key=c is t.primary_key,
                    )
                    for c in t.columns
                ],
                primary_key=[t.primary_key.name],
                foreign_keys=[
                    ForeignKey(column=fk.name, foreign_table=fk.references, foreign_column="id")
                    for fk in t.foreign_keys
                ],
            )
        schema = Schema(tables=tables)
        csi = mapping_to_csi(ConfigManager.generate_default_config(schema), schema)
        relationships = {
            (r["type"], r["fromEntity"], r["toEntity"]) for r in csi["conceptualModel"]["relationships"]
        }
        assert ("employeesToEmployees", "Employee", "Employee") in relationships
        assert ("employeesToDepartments", "Employee", "Department") in relationships


