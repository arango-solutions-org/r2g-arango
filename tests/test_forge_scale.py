# ── the stream contract (bounded memory) ─────────────────────────────────────


class TestStreamContract:
    def test_is_a_lazy_iterator_not_a_collection(self):
        stream = stream_rows(skeleton_plan(), 1, 5)
        assert isinstance(stream, GeneratorType)
        assert not isinstance(stream, (list, tuple, dict))

    def test_yields_its_first_rows_without_building_the_rest(self):
        """A trillion rows per entity: anything that held or pre-built the rows
        would never return. The stream hands back its first thousand at once."""
        scale = ForgeScale.from_document(
            {
                "rows": {"Account": 10**12, "Contact": 10**12, "Ticket": 10**12},
                "relationships": {"contactsToAccounts": {"distribution": "zipf", "exponent": 1.1}},
            }
        )
        first = list(itertools.islice(stream_rows(skeleton_plan(), 3, 1, scale), 1000))
        assert [r["id"] for _, r in first] == list(range(1, 1001))
        assert {t for t, _ in first} == {"accounts"}

    def test_traced_memory_does_not_grow_with_the_rows(self):
        """Python-level allocations while consuming 20x more rows stay flat:
        the stream keeps nothing it yielded (a list of the rows would be
        tens of MB here)."""
        plan = org_plan()
        scale_small = ForgeScale.from_document({"rows": {"Department": 100, "Employee": 10_000}})
        scale_big = ForgeScale.from_document({"rows": {"Department": 100, "Employee": 200_000}})

        def peak(scale: ForgeScale) -> int:
            tracemalloc.start()
            try:
                for _ in stream_rows(plan, 5, 1, scale):
                    pass
                return tracemalloc.get_traced_memory()[1]
            finally:
                tracemalloc.stop()

        small, big = peak(scale_small), peak(scale_big)
        assert big < 200_000, f"peak {big} bytes while streaming 200k rows"
        assert big < small * 3 + 100_000, (small, big)

    def test_the_stream_is_what_synthesize_rows_collects(self):
        plan = skeleton_plan()
        scale = ForgeScale.from_document(
            {"relationships": {"ticketsToContacts": {"distribution": "zipf", "exponent": 0.8}}}
        )
        collected: Dict[str, List[Dict]] = {t.table: [] for t in plan.tables}
        for table, row in stream_rows(plan, 11, 25, scale):
            collected[table].append(row)
        assert collected == synthesize_rows(plan, 11, 25, scale)

    def test_plan_order_parents_first(self):
        tables = [t for t, _ in stream_rows(skeleton_plan(), 1, 3)]
        assert tables == ["accounts"] * 3 + ["contacts"] * 3 + ["tickets"] * 3


