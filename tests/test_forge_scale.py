def test_csv_reader_round_trip_of_values():
    """csv_value's output is what the csv module (and so the engines' CSV
    readers) parse back, for every synthesized type."""
    from r2g.forge.dialects.base import csv_value

    line = ",".join(csv_value(v) for v in [7, 0.125, True, False, "x, y", None])
    assert next(csv.reader(io.StringIO(line))) == ["7", "0.125", "true", "false", "x, y", "\\N"]


def test_a_foreign_key_onto_a_non_key_column_is_refused():
    """The stream knows a parent's ids only as its primary key 1..n; an FK
    naming another column is refused by name (0.10.0 failed with KeyError)."""
    from dataclasses import replace

    plan = skeleton_plan()
    contacts = plan.table("contacts")
    columns = tuple(
        replace(c, references_column="account_name") if c.name == "account_id" else c
        for c in contacts.columns
    )
    bad = replace(
        plan, tables=tuple(replace(t, columns=columns) if t is contacts else t for t in plan.tables)
    )
    with pytest.raises(ForgeError, match=r"accounts\(account_name\), which is not"):
        stream_rows(bad, 1, 3)
